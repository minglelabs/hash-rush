#!/usr/bin/env python3
"""Packs the web game's free-for-all policy for Roblox.

A Roblox script cannot read a file, and its source should stay under about
190,000 characters, so the weights travel as ModuleScripts:

  src/server/weights/RLSolo.luau     what the numbers are: meta, heads, tensor sizes
  src/server/weights/RLSolo01.luau   the numbers themselves, base64 of the
  src/server/weights/RLSolo02.luau   little-endian half floats, in tensor order
  ...

RLPolicy.luau puts them back together. Run from anywhere:

  python3 roblox/tools/pack_weights.py
"""

import base64
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "src" / "ai" / "rl-solo.bin"
OUT = ROOT / "roblox" / "src" / "server" / "weights"
NAME = "RLSolo"
# Base64 characters per module: a multiple of 4 whose bytes are whole half floats.
CHUNK = 180_000
# In the file but not needed to play: the heads again, and the value estimate.
SKIP = ("heads", "v.weight", "v.bias")
NOTE = "-- Generated by roblox/tools/pack_weights.py from src/ai/rl-solo.bin. Do not edit.\n"


def lua(value, indent=1):
    """A JSON value as a Luau literal."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return json.dumps(value)
    tabs = "\t" * indent
    if isinstance(value, list):
        return "{ " + ", ".join(lua(v, indent) for v in value) + " }"
    rows = "".join(f"{tabs}\t{k} = {lua(v, indent + 1)},\n" for k, v in value.items())
    return "{\n" + rows + tabs + "}"


def main():
    raw = SOURCE.read_bytes()
    (size,) = struct.unpack_from("<I", raw, 0)
    head = json.loads(raw[4 : 4 + size])
    at = 4 + size
    kept = []
    halves = bytearray()
    for name, count in head["tensors"]:
        if name not in SKIP:
            kept.append([name, count])
            halves += raw[at : at + 2 * count]
        at += 2 * count
    assert at == len(raw), "the header and the file disagree about its length"

    text = base64.b64encode(bytes(halves)).decode("ascii")
    chunks = [text[i : i + CHUNK] for i in range(0, len(text), CHUNK)]

    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob(f"{NAME}*.luau"):
        old.unlink()
    tensors = "".join(f"\t\t{{ {json.dumps(n)}, {c} }},\n" for n, c in kept)
    index = (
        NOTE
        + "-- What rl-solo.bin holds; the numbers are in the modules beside this one.\n"
        + "return {\n"
        + f"\tmeta = {lua(head['meta'])},\n"
        + f"\theads = {lua(head['heads'])},\n"
        + "\t-- Name and size of each tensor, in the order the numbers come.\n"
        + "\ttensors = {\n" + tensors + "\t},\n"
        + f"\t-- Modules {NAME}01 to {NAME}{len(chunks):02d}.\n"
        + f"\tchunks = {len(chunks)},\n"
        + "}\n"
    )
    (OUT / f"{NAME}.luau").write_text(index)
    for i, chunk in enumerate(chunks, 1):
        (OUT / f"{NAME}{i:02d}.luau").write_text(f'{NOTE}return "{chunk}"\n')
    longest = max(len(NOTE) + len(c) + 10 for c in chunks)
    print(f"{len(halves) // 2} numbers in {len(chunks)} modules under {OUT.relative_to(ROOT)}, the longest {longest} characters")


if __name__ == "__main__":
    main()
