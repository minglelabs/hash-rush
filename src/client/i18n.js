// Picks the right Korean subject particle for a name: 구름이 / 초코가.
function koSubject(name) {
  const code = name.charCodeAt(name.length - 1);
  const hangul = code >= 0xac00 && code <= 0xd7a3;
  return name + (hangul && (code - 0xac00) % 28 ? '이' : '가');
}

